def branded_swagger_html(openapi_url: str, title: str = "agentops API") -> HTMLResponse:
    """Return a Swagger UI page with the agentops dark theme."""
    html = get_swagger_ui_html(
        openapi_url=openapi_url,
        title=title,
        swagger_ui_parameters={
            "deepLinking": True,
            "displayRequestDuration": True,
            "docExpansion": "list",
            "filter": True,
            "showExtensions": True,
            "showCommonExtensions": True,
            "persistAuthorization": True,
            "syntaxHighlight.theme": "monokai",
        },
    )
    # Inject the brand CSS just before </head> and a header banner.
    body = html.body.decode("utf-8") if isinstance(html.body, bytes) else html.body
    inject = (
        _BRAND_CSS
        + '<div style="background:linear-gradient(90deg,#5b6cff,#8a5bff);'
        'padding:12px 24px;color:#fff;font-family:system-ui;font-size:14px;">'
        '<strong>agentops</strong> — multi-tenant telephony &amp; AI platform. '
        'v1 API. <a href="/v1/docs/postman.json" style="color:#fff;text-decoration:underline">Download Postman collection</a>.</div>'
    )
    if "</head>" in body:
        body = body.replace("</head>", inject + "</head>", 1)
    else:
        body = inject + body
    return HTMLResponse(content=body, status_code=html.status_code)
